        $(document).ready(function() {
            $('#enviar_form').click(function(event) {
                event.preventDefault();
                $.ajax({
                    type: "post",
                    url: "{{ route('vacantes.store') }}",
                    data: $('#form_register').serialize(),
                    dataType: "json",
                    beforeSend: function() {
                        $('#enviar_form').html('Enviando...');
                        $('#enviar_form').prop("disabled", true);
                    },
                    success: function(res) {
                        if (res.success == false) {
                            pintar_errores(res.errors);
                        }
                        if (res.success == true) {
                            $('#form_register').trigger('reset');
                            $('#alerta').modal('show');
                        }
                    }
                }).always(function() {
                    $('#enviar_form').html('Enviar');
                    $('#enviar_form').prop("disabled", false);
                });
            });

            $('#oficina').change(function(e) {
                e.preventDefault();
                var oficina = $(this).val();
                switch (oficina) {
                    case 'cdmx':
                        $('#direccion_label').html(
                            'Heriberto Frías #408, Interior 3, Colonia Narvarte Poniente CDMX. CP: 03020'
                        );
                        break;
                    case 'puerto_vallarta':
                        $('#direccion_label').html(
                            'Av Francisco Medina Ascencio, Edificio Obelisco, departamento 101; Zona Hotelera, Las glorias CP: 48333'
                        );
                        break;
                    case 'puebla':
                        $('#direccion_label').html('Boulevard 5 de Mayo 7b Col. Las Palmas');
                        break;
                    case 'guadalajara':
                        $('#direccion_label').html('Av. Chapultepec Sur 284 interior #203 Col. Americana');
                        break;
                    default:
                        $('#direccion_label').html(
                            '');
                }
            });

            function pintar_errores(errores = null) {
                $(".errors").html('');
                $(".errors").parent().removeClass('has-error');
                $.each(errores, function(k, v) {
                    $(".error-" + k).html(v + ' <br/>');
                    $(".error-" + k).parent().addClass('has-error');
                });
            }
        });
